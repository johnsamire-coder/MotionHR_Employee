"""
Update Simulation Plan with Manager Tracking Scenarios
"""
from pathlib import Path

PLAN_FILE = Path("SIMULATION_PLAN.md")
CHECKLIST_FILE = Path("SCENARIOS_CHECKLIST.md")

# قراءة الخطة الحالية
plan_text = PLAN_FILE.read_text(encoding="utf-8")

# سيناريوهات جديدة للتراكنج
tracking_section = """
#### 🎯 سيناريو 11: تتبع مباشر من المدير
- [ ] المدير يفتح "Live Locations"
- [ ] التحقق من ظهور مواقع كل الموظفين الميدانيين النشطين
- [ ] التحقق من تحديث المواقع كل فترة (اختبار Real-time)
- [ ] النقر على موظف لعرض تفاصيله

#### 🎯 سيناريو 12: تراكنج موظف في مهمة
- [ ] المدير ينشئ مهمة لموظف ميداني
- [ ] الموظف يبدأ المهمة (Start Mission)
- [ ] المدير يفتح تفاصيل المهمة
- [ ] **التحقق من:**
  - عرض موقع الموظف الحالي
  - عرض مسار الموظف من البداية للنهاية
  - عرض الوقت المستغرق في كل نقطة
  - المسافة المقطوعة
- [ ] الموظف ينهي المهمة
- [ ] المدير يشوف تقرير كامل بالمسار

#### 🎯 سيناريو 13: Location History للموظف
- [ ] المدير يفتح "تقرير المواقع"
- [ ] اختيار موظف ميداني معين
- [ ] اختيار تاريخ محدد
- [ ] **التحقق من:**
  - عرض كل النقاط اللي المرت بها الموظف
  - المدة في كل مكان
  - عرض على خريطة
  - إمكانية تصدير التقرير (PDF/Excel)

#### 🎯 سيناريو 14: تنبيه عند خروج الموظف من المنطقة المحددة
- [ ] موظف ميداني له مهمة في منطقة X
- [ ] الموظف يخرج من منطقة المهمة
- [ ] **التحقق من:**
  - تنبيه للمدير
  - تسجيل الحادثة في اللوج
"""

# نضيفهم قبل "### المرحلة 5"
marker = "### المرحلة 5️⃣: سيناريوهات الإجازات"
if marker in plan_text:
    new_text = plan_text.replace(marker, tracking_section + "\n---\n\n" + marker)
    PLAN_FILE.write_text(new_text, encoding="utf-8")
    print("[OK] تم إضافة سيناريوهات التراكنج للخطة")
else:
    print("[WARN] لم يتم العثور على مكان الإدراج")

# تحديث الـ Checklist
checklist_text = CHECKLIST_FILE.read_text(encoding="utf-8")

old_field = """## 🔥 سيناريوهات المهام (5)

- [ ] موظف في زيارة وقت الحضور
- [ ] موظف مكتب من بره الشركة
- [ ] موظف مشي قبل انتهاء المهمة
- [ ] مهمة مستمرة لليوم التاني
- [ ] زيارات متعددة في يوم"""

new_field = """## 🔥 سيناريوهات المهام (5)

- [ ] موظف في زيارة وقت الحضور
- [ ] موظف مكتب من بره الشركة
- [ ] موظف مشي قبل انتهاء المهمة
- [ ] مهمة مستمرة لليوم التاني
- [ ] زيارات متعددة في يوم

## 📍 سيناريوهات التراكنج (4)

- [ ] Live Locations - عرض مباشر
- [ ] تراكنج موظف في مهمة (مسار كامل)
- [ ] Location History بتاريخ محدد
- [ ] تنبيه عند خروج من المنطقة"""

if old_field in checklist_text:
    new_checklist = checklist_text.replace(old_field, new_field)
    CHECKLIST_FILE.write_text(new_checklist, encoding="utf-8")
    print("[OK] تم تحديث الـ Checklist")

print("\n[DONE] الخطة والـ Checklist محدّثين")
